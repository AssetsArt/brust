// `brust build` (spec S5, plan T6): route entry → compiler → `dist/` + `manifest.json`.
// `dist/` is always regenerated from scratch; nothing in it is edited by hand.
import { cpSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { join, relative, resolve } from 'node:path'
import { flattenRoutes } from '../routes'
import { buildClientChunks, buildJobs, buildReactChunks, buildRuntime } from './bundle'
import { compileApp } from './compile'
import { writeManifest } from './manifest'
import { scanRoutes } from './scan'

export { BuildError } from './errors'

/** The napi addon(s) next to this package (`native/brust.<plat>.node`, built by `napi build`). */
const NATIVE_DIR = resolve(import.meta.dir, '../../native')

export async function runBuild(opts: { appRoot: string; entry: string; outDir: string; log: (s: string) => void }): Promise<void> {
  const appRoot = resolve(opts.appRoot)
  const entry = resolve(appRoot, opts.entry)
  const dist = resolve(appRoot, opts.outDir)
  rmSync(dist, { recursive: true, force: true })
  mkdirSync(dist, { recursive: true })

  // The runtime first: its hashed URL is the `runtimeImport` every client chunk is compiled with.
  const runtime = await buildRuntime(dist)
  const { routes, componentFile } = await scanRoutes(entry)
  const { leaves } = flattenRoutes(routes)
  const { compiled, routeComponent } = compileApp({
    appRoot,
    leaves,
    componentFile,
    runtimeImport: `/_brust/${runtime}`,
    serverOnly: [],
    log: opts.log,
  })

  mkdirSync(join(dist, 'jinja'), { recursive: true })
  for (const c of compiled.values()) writeFileSync(join(dist, 'jinja', `${c.id}.jinja`), c.jinja)

  const sourceDirOf = new Map<string, string>()
  const chunks = new Map([...(await buildClientChunks(dist, compiled, sourceDirOf)), ...(await buildReactChunks(dist, compiled))])
  await buildJobs(dist, compiled, sourceDirOf)

  const manifest = writeManifest({ leaves, routeComponent, compiled, runtime, chunks })
  writeFileSync(join(dist, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`)

  const pub = join(appRoot, 'public')
  if (existsSync(pub)) cpSync(pub, join(dist, 'public'), { recursive: true })
  if (existsSync(NATIVE_DIR)) {
    mkdirSync(join(dist, 'native'), { recursive: true })
    for (const f of readdirSync(NATIVE_DIR)) if (f.endsWith('.node')) cpSync(join(NATIVE_DIR, f), join(dist, 'native', f))
  }
  const entryRel = relative(dist, entry)
  writeFileSync(
    join(dist, 'index.js'),
    [
      '// generated by `brust build` — `bun dist/index.js` starts the app (do not edit)',
      "import { join } from 'node:path'",
      "process.env.BRUST_PREBUILT = '1'",
      'process.env.BRUST_DIST_DIR = import.meta.dir',
      `process.env.BRUST_APP_ENTRY = join(import.meta.dir, ${JSON.stringify(entryRel)})`,
      "const { run } = await import('@brust/brust')",
      'await run()',
      '',
    ].join('\n'),
  )
  rmSync(join(dist, '.stage'), { recursive: true, force: true })
}
