// The generated Cloudflare entry (M4-CF spec §4, R9, R13): ~25 lines that wire the user's routes, jobs and
// actions into the six exports the wasm glue imports from `./brust-app.js`. Pure: text in, text out.
export interface CfConfigJson {
  abi: 1
  generator: string
  l1Capacity: number
  jobCacheCapacity: number
  stats: boolean
  edgeCache: 'off'
  cors?: unknown
  /** F539 `[csp]` (optional under abi 1, like `cache`): Rust `CfCsp`, `reportOnly` for `mode = "report-only"`. F544: present
   * whenever brust.toml has the table, `enabled` false when it is off (the Worker's `BRUST_CSP_MODE` binding may turn it on). */
  csp?: {
    enabled: boolean
    reportOnly: boolean
    scriptSrc?: string[]
    scriptSrcUnsafe?: boolean
    styleSrc?: string[]
    connectSrc?: string[]
    imgSrc?: string[]
    fontSrc?: string[]
    frameAncestors?: string[]
    reportUri?: string
    defaultSrc?: 'self' | 'none'
    baseUri?: 'self' | 'none'
    formAction?: string[]
    frameSrc?: string[]
    mediaSrc?: string[]
    workerSrc?: string[]
    manifestSrc?: string[]
    objectSrc?: string[]
  }
  /** F475: `stream` + `maxStreamBytes` only when the app lists streamed routes; the idle/total timeouts and `maxStreams` are the platform's on Workers. */
  actions?: { prefix: string; maxBodyBytes: number; maxResponseBytes: number; crossSite: 'reject' | 'allow'; stream?: string[]; maxStreamBytes?: number }
  /** The cache adapter (optional under abi 1, cache adapters R13). */
  cache?: { adapter: string; getTimeoutMs: number; maxBodyBytes: number; namespace: string; buildId: string; epochIntervalMs: number }
}

/** The cache adapter wiring of the entry: absent → the entry is byte-identical to the no-cache one (D3). */
export interface CfEntryCache {
  /** The adapter module (an absolute path, or a built-in package spec). */
  module: string
  options: Record<string, unknown>
  /** A composed built-in broadcast's package spec. */
  broadcast?: string
  broadcastOptions?: Record<string, unknown>
}

export interface CfEntryInput {
  /** absolute paths; each goes through JSON.stringify */
  entry: string
  jobsEntry: string
  actionsEntry: string | null
  /** L16: no pages: the routes module and the jobs module are not imported; the handlers serve an empty route table. */
  actionsOnly?: boolean
  prefix: string
  manifestPath: string
  templatesPath: string
  config: CfConfigJson
  cache?: CfEntryCache | null
  /** A Durable Object is configured: the entry re-exports `BrustCacheDO` (R1; `worker/main.js` re-exports it from this one module). */
  doClass?: boolean
}

export function cfEntrySource(i: CfEntryInput): string {
  const q = JSON.stringify
  const actions = i.actionsEntry !== null
  const c = i.cache ?? null
  const pages = i.actionsOnly !== true
  return `${[
    '// generated by `brust build --target cloudflare` — do not edit (M4-CF spec §4)',
    ...(pages ? [`import * as R from ${q(i.entry)}`, `import J, * as JM from ${q(i.jobsEntry)}`] : []),
    ...(actions ? [`import A from ${q(i.actionsEntry)}`] : []),
    `import M from ${q(i.manifestPath)}`,
    `import T from ${q(i.templatesPath)}`,
    `import { fetchInScope, flattenRoutes, jsonCall, makeHandlers, noActions } from "@brust/core/server-handlers"`,
    'import { env as ENV } from "cloudflare:workers"',
    ...(actions ? ['import { mountActions } from "@brust/core/server-handlers/actions"'] : []),
    pages
      ? 'const h = makeHandlers({ leaves: flattenRoutes(R.routes ?? R.default).leaves, jobs: J, manifest: M, stores: JM.stores ?? {} })'
      : 'const h = makeHandlers({ leaves: [], jobs: {}, manifest: M, stores: {} })',
    // F529 (D3): a Worker has no sockets; `.ws()` fails here, at startup, with this message rather than at the first request.
    ...(actions
      ? [
          `const app = mountActions(A, ${q(i.prefix)})`,
          'if (app["~hasWS"]) throw new Error("WebSocket (.ws()) is not supported on --target cloudflare: a Worker has no sockets; use --target bun")',
          'app.compile() // startup-phase compile (R9)',
        ]
      : []),
    'export const loader = jsonCall(h.loader)',
    'export const jobs = jsonCall(h.jobs)',
    actions ? 'export const action = (req) => fetchInScope(app, req)' : 'export const action = noActions',
    'export const MANIFEST = JSON.stringify(M)',
    'export const TEMPLATES = T',
    ...(c
      ? [
          `import CACHE from ${q(c.module)}`,
          ...(c.broadcast ? [`import CACHE_BROADCAST from ${q(c.broadcast)}`] : []),
          'import { waitUntil } from "cloudflare:workers"',
          'import { install as installRuntime } from "@brust/core/server-handlers"',
          `export const install = (rt) => installRuntime(rt, { adapter: CACHE, options: ${JSON.stringify(c.options)}, ${c.broadcast ? `broadcast: CACHE_BROADCAST, broadcastOptions: ${JSON.stringify(c.broadcastOptions ?? {})}, ` : ''}config: ${JSON.stringify(i.config.cache)}, waitUntil })`,
        ]
      : ['export { install } from "@brust/core/server-handlers"']),
    ...(i.doClass ? ['export { BrustCacheDO } from "@brust/cache-cloudflare/do"'] : []),
    `export const CONFIG = ${q(JSON.stringify(i.config))}`,
    // F544: the Worker's BRUST_CSP_MODE binding (off | report-only | enforce); the core applies it to CONFIG.csp at boot.
    'export const CSP_MODE = ENV?.BRUST_CSP_MODE',
  ].join('\n')}\n`
}
