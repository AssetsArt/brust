// `brust build --actions-only` (gaps round L16, R16.3/R16.4): a dist with NO page routes: the actions app behind
// the same Rust admission (method gate, body caps, `Content-Encoding`, the cross-site guard, CORS), every other
// path a 404 problem+json. With `--target cloudflare` it also writes `<out>/cf/`: a Worker serving only actions
// (no Static Assets). The routes entry is neither read nor required.
import { existsSync, mkdirSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import { basename, dirname, isAbsolute, join, relative, resolve } from 'node:path'
import { buildActions } from './bundle'
import { type CfPrepared, buildCloudflare, prepareCloudflare } from './cloudflare'
import type { ActionsBuildConfig, BuildConfig } from './config'
import { BuildError } from './errors'
import { MANIFEST_VERSION, type ManifestJson } from './manifest'

const MARKER = '.brust'

export async function runActionsOnly(o: {
  appRoot: string
  dist: string
  config: BuildConfig
  target: 'bun' | 'cloudflare' | 'static' | undefined
  wasmFromSource: boolean
  statOk: (p: string) => boolean
  assertSafeOutDir: (dist: string, appRoot: string, keep: string[]) => void
  log: (s: string) => void
}): Promise<void> {
  const { appRoot, dist, config } = o
  const actions: ActionsBuildConfig | null = config.actions
  if (!actions) throw new BuildError('actions-only', '--actions-only needs an [actions] table in brust.toml')
  if (o.target === 'static') throw new BuildError('actions-only', '--actions-only builds no pages: it cannot be combined with --target static')
  const entry = resolve(appRoot, actions.entry)
  const rel = relative(appRoot, entry)
  if (isAbsolute(actions.entry) || rel === '..' || rel.startsWith('../') || isAbsolute(rel) || !o.statOk(entry))
    throw new BuildError('actions-entry', `actions.entry ${actions.entry} is not a file inside the app`)
  o.assertSafeOutDir(dist, appRoot, [entry])
  if (config.cache) o.log('[brust] actions-only: [cache] and route options do not apply (ignored)')
  if (actions.baseUrl !== undefined) o.log('[brust] actions-only: [actions] base_url is for the pages that call these actions (ignored here)')
  const cf: CfPrepared | null = o.target === 'cloudflare' ? await prepareCloudflare(appRoot, config.cloudflare, { fromSource: o.wasmFromSource, env: process.env }) : null

  const tmp = join(dirname(dist), `.${basename(dist)}.brust-tmp`)
  rmSync(tmp, { recursive: true, force: true })
  mkdirSync(tmp, { recursive: true })
  try {
    const manifest: ManifestJson = {
      version: MANIFEST_VERSION,
      routes: [],
      components: {},
      assets: { runtime: '', features: {} },
      jobs_module: 'jobs.js',
      actions: { entry: await buildActions(tmp, entry), prefix: actions.prefix, maxBodyBytes: actions.maxBodyBytes, maxResponseBytes: actions.maxResponseBytes, crossSite: actions.crossSite },
      actions_only: true,
    }
    mkdirSync(join(tmp, 'jinja'), { recursive: true })
    writeFileSync(join(tmp, 'jobs.js'), '// generated by `brust build --actions-only`: no pages, so no jobs\nexport default {}\n')
    writeFileSync(join(tmp, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`)
    writeFileSync(join(tmp, MARKER), 'generated by `brust build`: this directory is replaced on every build\n')
    writeFileSync(
      join(tmp, 'index.js'),
      [
        '// generated by `brust build --actions-only` — `bun dist/index.js` serves the actions (do not edit)',
        "process.env.BRUST_PREBUILT = '1'",
        'process.env.BRUST_DIST_DIR = import.meta.dir',
        "const { run } = await import('@brust/core')",
        'await run()',
        '',
      ].join('\n'),
    )
    if (cf) {
      const warnings = await buildCloudflare(
        tmp,
        { appRoot, entry, dist, compiled: new Map(), manifest, sourceOf: new Map(), actionsEntry: entry, actionsOnly: true, log: o.log },
        cf,
      )
      for (const w of warnings) o.log(w)
    }
    rmSync(join(tmp, '.stage'), { recursive: true, force: true })
    if (existsSync(dist)) {
      const old = join(dirname(dist), `.${basename(dist)}.brust-old`)
      rmSync(old, { recursive: true, force: true })
      renameSync(dist, old)
      renameSync(tmp, dist)
      rmSync(old, { recursive: true, force: true })
    } else renameSync(tmp, dist)
  } catch (e) {
    rmSync(tmp, { recursive: true, force: true })
    throw e
  }
}
