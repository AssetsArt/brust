// `brust build --target static` with `[actions]` (gaps round L12, R12.1): the static tree plus a
// Cloudflare Pages advanced-mode Worker that serves ONLY the action prefix.
//   static/_worker.js/index.js   a WorkerEntrypoint: the action prefix -> the Cloudflare core, everything else -> env.ASSETS
//   static/_worker.js/core/      the `--target cloudflare` worker tree (glue + wasm + brust-app.js), verbatim
//   static/_routes.json          include: the prefix only, so pages and assets never invoke the Worker
//   wrangler.jsonc         the Pages project file (name, compatibility date); sits next to `static/`
import { cpSync, existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { type CfPrepared, cacheNeeds } from './cloudflare'
import { workerNameOf } from './cf-wrangler'
import { BuildError } from './errors'
import { CF_MIN_COMPAT_DATE } from './config'
import type { CacheRecord } from './manifest'

/** `_routes.json` (R12.1): the prefix itself and everything under it; nothing else reaches the Worker. */
export function routesJson(prefix: string): string {
  return `${JSON.stringify({ version: 1, include: [prefix, `${prefix}/*`], exclude: [] }, null, 2)}\n`
}

/** `_worker.js/index.js`. Pages' pipeline wants a module object with `fetch`, not the class the core
 * exports (a WorkerEntrypoint whose `fetch` reads `this.env` and `this.ctx`), so the core's method is
 * called with exactly those two. A request that reaches the Worker and is not an action (a path
 * `_routes.json` keeps away, or a probe) falls through to the static files. */
export function workerSource(main: string, prefix: string): string {
  const q = JSON.stringify
  return `${[
    '// generated by `brust build --target static` (actions on Pages) — do not edit',
    `import Core from ${q(`./core/${main}`)}`,
    `const PREFIX = ${q(prefix)}`,
    'export default {',
    '  fetch(request, env, ctx) {',
    '    const path = new URL(request.url).pathname',
    '    if (path === PREFIX || path.startsWith(`${PREFIX}/`)) return Core.prototype.fetch.call({ env, ctx }, request)',
    '    return env.ASSETS.fetch(request)',
    '  },',
    '}',
  ].join('\n')}\n`
}

/** The Pages project file: bindings and secrets are the user's (`wrangler pages` / the dashboard), never baked. */
export function pagesConfig(p: CfPrepared): string {
  const name = p.cfg.name ?? (p.pkgName ? workerNameOf(p.pkgName) : undefined)
  const compatibilityDate = p.cfg.compatibilityDate ?? p.core.meta.compatibilityDate
  if (compatibilityDate < CF_MIN_COMPAT_DATE) throw new BuildError('config', `compatibility_date ${compatibilityDate} is older than ${CF_MIN_COMPAT_DATE}`)
  const c = { ...(name !== undefined ? { name } : {}), pages_build_output_dir: './static', compatibility_date: compatibilityDate }
  return `// generated by \`brust build --target static\` — bindings and secrets: \`wrangler pages secret put\` / the dashboard (docs/cloudflare.md §12)\n${JSON.stringify(c, null, 2)}\n`
}

/** R12: `[cache]` does not apply to static pages, and the Worker serves actions only, so an adapter
 * that needs a Cloudflare binding (KV, Durable Object) has nowhere to be used: refused before any write. */
export function assertNoCacheBindings(cache: Pick<CacheRecord, 'adapter' | 'broadcast' | 'options' | 'broadcastOptions'> | null | undefined): void {
  const need = cacheNeeds(cache ?? undefined)
  if (need)
    throw new BuildError(
      'ssg-actions-cache',
      `[cache] adapter "${cache!.adapter}" needs a Cloudflare binding (${[need.kv && `KV ${need.kv}`, need.do && `Durable Object ${need.do}`].filter(Boolean).join(', ')}), which the static + actions Worker does not carry (static pages are never cached, the Worker serves actions only); drop [cache], or use --target cloudflare`,
    )
}

/** Turns `<dist>/cf/` (built by `buildCloudflare`) into the Pages Worker inside `<dist>/static/`, then
 * drops `cf/`: the build is `--target static`, its only output is `static/`. */
export function writeStaticWorker(dist: string, actions: { prefix: string }, p: CfPrepared, log: (s: string) => void): void {
  const staticDir = join(dist, 'static')
  const worker = join(dist, 'cf', 'worker')
  if (!existsSync(join(worker, p.core.meta.main))) throw new BuildError('cf-wasm', `the Cloudflare build wrote no worker/${p.core.meta.main}`)
  const out = join(staticDir, '_worker.js')
  rmSync(out, { recursive: true, force: true })
  cpSync(worker, join(out, 'core'), { recursive: true })
  writeFileSync(join(out, 'index.js'), workerSource(p.core.meta.main, actions.prefix))
  writeFileSync(join(staticDir, '_routes.json'), routesJson(actions.prefix))
  writeFileSync(join(dist, 'wrangler.jsonc'), pagesConfig(p))
  const report = join(staticDir, 'ssg.json')
  const json = JSON.parse(readFileSync(report, 'utf8')) as Record<string, unknown>
  writeFileSync(report, `${JSON.stringify({ ...json, actions: { prefix: actions.prefix, worker: '_worker.js' } }, null, 2)}\n`)
  rmSync(join(dist, 'cf'), { recursive: true, force: true })
  log(`[brust] static: actions under ${actions.prefix} are served by _worker.js (_routes.json keeps pages and assets off the Worker)`)
}
