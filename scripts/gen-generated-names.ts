// F264: generates tests/fixtures/shadcn/repro/generated-names.tsx (F233): one component per (generated name, role) so a
// component binding named like a name brust's client chunk makes for itself is renamed around, never refused.
// The names come from `NAMES` in crates/brust-compiler/tests/generated_names.rs (the one source); the Chromium test
// (tests/server/generated-names.chromium.test.ts) keeps a copy that scripts/gen-generated-names.test.ts compares.
// `bun scripts/gen-generated-names.ts` writes the fixture (re-bless after the names change); `--check` exits 1 when stale.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = join(import.meta.dir, '..')
export const RS = join(root, 'crates/brust-compiler/tests/generated_names.rs')
export const CHROMIUM = join(root, 'tests/server/generated-names.chromium.test.ts')
export const OUT = join(root, 'tests/fixtures/shadcn/repro/generated-names.tsx')

export const ROLES = ['state', 'derived', 'handler', 'ref'] as const

/** The `NAMES` table of the cargo test, in order. Throws when it is missing or empty (a skipped setup must not read as a pass). */
export function rustNames(src = readFileSync(RS, 'utf8')): string[] {
  const m = src.match(/const NAMES: &\[&str\] = &\[([^\]]*)\];/)
  if (!m) throw new Error(`NAMES not found in ${RS}`)
  const names = [...(m[1] ?? '').matchAll(/"([^"]+)"/g)].map((x) => x[1] as string)
  if (names.length === 0) throw new Error(`NAMES in ${RS} is empty`)
  return names
}

/** The copy of the table in the Chromium test. */
export function chromiumNames(src = readFileSync(CHROMIUM, 'utf8')): string[] {
  const m = src.match(/const NAMES = \[([^\]]*)\]/)
  if (!m) throw new Error(`NAMES not found in ${CHROMIUM}`)
  return [...(m[1] ?? '').matchAll(/'([^']+)'/g)].map((x) => x[1] as string)
}

const HEADER = `// F233: every name brust's client chunk generates on its own (runtime imports, the behaviour context, the paint
// helpers, the handler wrapper's rest parameter, member names), taken by a component's state, derived value, handler
// and ref. Each component paints with every helper, has a keyed list, a useId, an effect with deps and a linked child,
// so its chunk prints every generated name. Served, each one counts like React (click: +1, the derived value doubles).
// One component per (name, role). GENERATED by scripts/gen-generated-names.ts from NAMES in
// crates/brust-compiler/tests/generated_names.rs: run \`bun scripts/gen-generated-names.ts\` to re-bless it after the names
// change (\`--check\` fails when it is stale). Keep NAMES in tests/server/generated-names.chromium.test.ts in sync.
import { useEffect, useId, useRef, useState } from 'react'

function Show({ v }: { v: number }) {
  return <i data-testid="show">{v}</i>
}
`

function component(name: string, role: (typeof ROLES)[number]): string {
  // the state the count lives in, the value the markup shows, and the click handler, per role
  const decl: Record<string, string> = {
    state: `  const [n, setN] = useState(0)\n  const [${name}, setV] = useState(0)\n`,
    derived: `  const [n, setN] = useState(0)\n  const ${name} = n * 2\n`,
    handler: `  const [n, setN] = useState(0)\n  const ${name} = () => setN(n + 1)\n`,
    ref: `  const [n, setN] = useState(0)\n  const ${name} = useRef<HTMLElement>(null)\n`,
  }
  const v = role === 'state' ? name : 'n'
  const shown = role === 'state' || role === 'derived' ? name : 'n'
  const onClick = { state: `() => setV(${name} + 1)`, derived: '() => setN(n + 1)', handler: name, ref: `() => setN(n + (${name}.current ? 1 : 100))` }[role]
  const refAttr = role === 'ref' ? ` ref={${name}}` : ''
  return `function C${name}_${role}() {
${decl[role]}  const id = useId()
  useEffect(() => {
    document.body.dataset.last = String(${v})
  }, [${v}])
  return (
    <div id={id} data-testid="${name}-${role}">
      <b onClick={${onClick}}${refAttr} title={'t' + ${v}} style={{ width: ${v} }} aria-label={${v} > 1} download={${v} > 2} hidden={${v} > 3}>
        {${shown}}
      </b>
      <ul>
        {[1, 2].map((i) => (
          <li key={i}>{i + ${v}}</li>
        ))}
      </ul>
      <Show v={${v}} />
    </div>
  )
}
`
}

export function generate(names = rustNames()): string {
  const parts = [HEADER]
  for (const name of names) for (const role of ROLES) parts.push(component(name, role))
  const page = names.flatMap((name) => ROLES.map((role) => `      <C${name}_${role} />`)).join('\n')
  parts.push(`export default function Page() {\n  return (\n    <main>\n${page}\n    </main>\n  )\n}\n`)
  return parts.join('\n')
}

if (import.meta.main) {
  const want = generate()
  if (process.argv.includes('--check')) {
    if (readFileSync(OUT, 'utf8') !== want) {
      console.error('tests/fixtures/shadcn/repro/generated-names.tsx is stale: run `bun scripts/gen-generated-names.ts`')
      process.exit(1)
    }
  } else {
    writeFileSync(OUT, want)
    console.log(`wrote ${OUT}`)
  }
}
