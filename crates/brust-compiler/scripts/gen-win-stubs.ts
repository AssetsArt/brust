#!/usr/bin/env bun
// crates/brust-compiler/scripts/gen-win-stubs.ts — writes src/parse/stubs/windows.rs (ledger F484, plan amendment A2).
//
//   bun crates/brust-compiler/scripts/gen-win-stubs.ts <link-log> --run <ci-run-id>   regenerate windows.rs
//   bun crates/brust-compiler/scripts/gen-win-stubs.ts <link-log> --check             exit 1 if the log names an uncovered symbol
//
// <link-log> is the output of the ci.yml `windows-native` job's failed (LNK1120) link of brust-napi on x86_64-pc-windows-msvc
// (download the job log). Every "unresolved external symbol <name>" becomes an abort stub, except the names windows_real.rs
// defines for real (REAL). The file is generated whole: never edit it by hand, rerun this after a Bun crates bump.
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const REAL = new Set(['simdutf__convert_valid_utf16le_to_utf8', 'bun_is_stdio_null'])
const args = process.argv.slice(2)
const logPath = args[0]
const check = args.includes('--check')
const run = args[args.indexOf('--run') + 1]
if (!logPath || (!check && (!args.includes('--run') || !run))) {
  console.error('usage: gen-win-stubs.ts <link-log> --run <ci-run-id> | <link-log> --check')
  process.exit(2)
}

// rustc relays link.exe output coloured and with Windows line ends.
// biome-ignore lint/suspicious/noControlCharactersInRegex: the ESC byte is what is matched
const log = readFileSync(logPath, 'utf8').replace(/\x1b\[[0-9;]*m/g, '').replace(/[\r␍]/g, '')
const names = new Set<string>()
for (const m of log.matchAll(/unresolved external symbol (\S+)/g)) names.add(m[1] as string)

const root = resolve(import.meta.dir, '../../..')
const file = resolve(import.meta.dir, '../src/parse/stubs/windows.rs')

if (check) {
  const have = new Set(readFileSync(file, 'utf8').split('\n').map((l) => l.trim()).filter((l) => /^[A-Za-z_]\w*$/.test(l)))
  const missing = [...names].filter((n) => !have.has(n) && !REAL.has(n)).sort()
  if (missing.length) {
    console.error(`windows.rs lacks ${missing.length} symbol(s); regenerate:\n  ${missing.join('\n  ')}`)
    process.exit(1)
  }
  console.log(`windows.rs covers all ${names.size} unresolved symbol(s)`)
  process.exit(0)
}

const bad = [...names].filter((n) => !/^[A-Za-z_]\w*$/.test(n))
if (bad.length) throw new Error(`not a plain C identifier, cannot stub by macro: ${bad.join(' ')}`)
const rev = readFileSync(resolve(root, 'Cargo.lock'), 'utf8').match(/oven-sh\/bun\?rev=([0-9a-f]{40})/)?.[1]
if (!rev) throw new Error('Cargo.lock: no oven-sh/bun git rev')
const list = [...names].filter((n) => !REAL.has(n)).sort()

const out = `// GENERATED by crates/brust-compiler/scripts/gen-win-stubs.ts — do not edit by hand.
// Bun rev ${rev}, from the link log of CI run ${run} (ci.yml windows-native).
// Regenerate: bun crates/brust-compiler/scripts/gen-win-stubs.ts <link-log> --run <ci-run-id>
//
//! Windows (MSVC) only: abort stubs for the ${list.length} symbols the vendored Bun crates declare but only bun.exe's
//! C/C++ side (libuv, uSockets, zstd, BoringSSL, simdutf, highway, JSC/WTF) or \`bun_runtime\` defines.
//!
//! On macOS ld64 dead-strips every caller of these before resolving; on Linux an undefined symbol
//! in a shared object resolves lazily. MSVC's link.exe resolves every reference of every object it
//! pulls in before \`/OPT:REF\` discards anything, so it needs a definition for each (LNK1120).
//! brust never reaches them (ledger F484, plan amendment A2): their callers are dead on macOS, and
//! the Windows-only ones are Bun's event loop, stdio, tty and HTTP server, which brust does not
//! drive. A stub that is reached anyway aborts with its own name. Real definitions: windows_real.rs.

#[cold]
fn not_linked(name: &str) -> ! {
    eprintln!("brust: {name} reached (Bun's native side is not linked into brust on Windows)");
    std::process::abort();
}

macro_rules! abort_stubs {
    ($($name:ident)*) => {
        $(
            #[unsafe(no_mangle)]
            extern "C" fn $name() -> ! {
                not_linked(stringify!($name))
            }
        )*
    };
}

abort_stubs! {
${list.map((n) => `    ${n}`).join('\n')}
}
`
writeFileSync(file, out)
console.log(`windows.rs: ${list.length} abort stubs (${names.size} names in the log, ${names.size - list.length} real)`)
