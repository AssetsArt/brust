//! Client backend (spec §7.1): the react-free directive chunk, printed from
//! the IR — `defineBehavior(id, factory)` returning the members the template's
//! directives name.
use super::common::{
    DerivedShape, Facts, arrow_body, client_fn, client_js, import_lines, imports_in,
    module_code_with, module_names_in, store_client_js, visit_idents, visit_verbatim_captures,
};
use super::names::Names;
use super::{Member, MemberDef, Paint};
use crate::ir::{Attr, ComponentIR, Expr, IdentKind, Literal, Node, RawExpr, RawKind};
use std::collections::{BTreeSet, HashSet};

/// The chunk source, its members in export order, and the data modules whose imported list it declares projected
/// instead of importing (F362 PR2: the build keeps them only while no other client module imports them).
pub fn chunk(
    ir: &ComponentIR,
    members: &[Member],
    runtime_import: &str,
    seed: &HashSet<String>,
) -> (String, Vec<String>, Vec<String>) {
    chunk_in(ir, members, runtime_import, seed, false, true)
}

/// [`chunk`] importing every imported list as written (the build's fallback when a projected data module is still in
/// the client graph through another importer).
pub fn chunk_whole(
    ir: &ComponentIR,
    members: &[Member],
    runtime_import: &str,
    seed: &HashSet<String>,
) -> String {
    chunk_in(ir, members, runtime_import, seed, false, false).0
}

/// R34.124: the part of a specialised clone's chunk that does not name the clone: a module that exports the behaviour
/// factory (`export const behavior = ({ … }) => { … }`). Every clone whose factory is equal shares one such module; its
/// own chunk is [`stub`].
pub fn factory_module(
    ir: &ComponentIR,
    members: &[Member],
    runtime_import: &str,
    seed: &HashSet<String>,
) -> (String, Vec<String>) {
    // A shared factory imports its lists as written: one module serves several clones, with no fallback of its own.
    let (code, members, _) = chunk_in(ir, members, runtime_import, seed, true, false);
    (code, members)
}

/// A clone's own chunk: it registers the shared factory under the clone's id.
pub fn stub(id: &str, module: &str, runtime_import: &str) -> String {
    format!(
        "// generated by brust v2 — client chunk for {id}\nimport {{ defineBehavior }} from {}\nimport {{ behavior }} from {}\nexport default defineBehavior({}, behavior)\n",
        crate::ir::expr::js_string(runtime_import),
        crate::ir::expr::js_string(&format!("brust-spec:{module}")),
        crate::ir::expr::js_string(id)
    )
}

fn chunk_in(
    ir: &ComponentIR,
    members: &[Member],
    runtime_import: &str,
    seed: &HashSet<String>,
    shared: bool,
    project_imports: bool,
) -> (String, Vec<String>, Vec<String>) {
    let Some(structural) = ir.structural.as_deref() else {
        return (String::new(), Vec::new(), Vec::new());
    };
    let mut f = Facts::new(ir, structural);
    // F233: every name the chunk declares on its own, renamed away from the component's names and the members'.
    let mut names = Names::new(seed);
    for m in members {
        names.reserve(&m.name);
        if let MemberDef::Value { bindings, .. }
        | MemberDef::List { bindings, .. }
        | MemberDef::Link { bindings, .. } = &m.def
        {
            bindings.iter().for_each(|b| names.reserve(b));
        }
        if let MemberDef::Key { item, .. } = &m.def {
            names.reserve(item);
        }
    }
    let n = ChunkNames::new(&mut names);
    f.rest = n.args.clone();
    f.props_fn = n.props.clone();
    let f = f;

    // Code roots: everything the chunk runs.
    let mut roots: Vec<&RawExpr> = Vec::new();
    let inits: Vec<Option<RawExpr>> = (0..ir.state.len()).map(|i| f.state_init(i)).collect();
    roots.extend(inits.iter().flatten());
    roots.extend(ir.handlers.iter().map(|h| &h.body));
    roots.extend(ir.effects.iter().map(|e| &e.body));
    // An effect's deps (printed in `void [...]`) and a ref's initial value (`__ref("r", init)`) run on the client too:
    // a derived value only they read is declared, and F362 scans them (Afrojack and Mellow, PR1 review).
    roots.extend(ir.effects.iter().flat_map(|e| e.deps.iter().flatten()));
    roots.extend(structural.refs.iter().filter_map(|r| match &r.init {
        Expr::Raw(raw) => Some(raw),
        _ => None,
    }));
    for m in members {
        match &m.def {
            MemberDef::Value { raw, .. }
            | MemberDef::List { raw, .. }
            | MemberDef::Key { raw, .. } => roots.push(raw),
            MemberDef::Link { props, .. } => roots.extend(props.iter().map(|(_, r)| r)),
        }
    }
    let event_locals = event_handlers(&ir.template)
        .into_iter()
        .filter(|h| !ir.handlers.iter().any(|d| &d.name == h))
        .collect::<Vec<_>>();
    let mut reached = f.reach(&roots);
    reached.extend(
        event_locals
            .iter()
            .filter(|n| f.derived.contains_key(*n))
            .cloned(),
    );
    let reached_raws: Vec<&RawExpr> = reached.iter().filter_map(|n| f.derived_raw(n)).collect();

    let mut imports = BTreeSet::new();
    let mut module_names = BTreeSet::new();
    for r in roots.iter().chain(&reached_raws) {
        imports_in(r, &mut imports);
        module_names_in(r, &f, &mut module_names);
    }
    // A prop read prints its default inline (`props().x === undefined ? dflt : props().x`): what the default reads is
    // the chunk's too (F337: Radix's `getValueLabel = defaultGetValueLabel`, a module function).
    let mut defaulted = BTreeSet::new();
    for r in roots.iter().chain(&reached_raws) {
        visit_idents(r, &mut |name, kind| {
            if *kind == IdentKind::Prop && f.prop_defaults.contains_key(name) {
                defaulted.insert(name.to_string());
            }
        });
    }
    for name in &defaulted {
        let d = &f.prop_defaults[name];
        imports_in(d, &mut imports);
        module_names_in(d, &f, &mut module_names);
    }
    // Store handles (M3-F D7): the chunk imports each one under the user's specifier; the bundler
    // resolves it against the component's source dir (C6). The job never imports a store module.
    let mut store_handles = BTreeSet::new();
    let mut views = BTreeSet::new();
    let effect_deps = ir.effects.iter().flat_map(|e| e.deps.iter().flatten());
    for r in roots
        .iter()
        .copied()
        .chain(reached_raws.iter().copied())
        .chain(effect_deps)
    {
        visit_idents(r, &mut |_, kind| {
            if let IdentKind::Store { handle, .. } = kind {
                store_handles.insert(handle.clone());
            }
        });
        // Verbatim code reads the view `s` as written: the chunk declares it.
        visit_verbatim_captures(r, &mut |name, kind| {
            if let IdentKind::Store { handle, key: None } = kind {
                views.insert((handle.clone(), name.to_string()));
            }
        });
    }
    for h in &store_handles {
        if let Some(u) = f.stores.get(h) {
            imports.insert(u.import.clone());
        }
    }
    module_names.extend(ir.client_module_locals.iter().cloned());
    // F362: a module list the rows run over ships the keys this chunk reads. `code` is everything printed below.
    let code: Vec<&RawExpr> = roots
        .iter()
        .copied()
        .chain(reached_raws.iter().copied())
        .collect();
    let lists: Vec<&RawExpr> = members
        .iter()
        .filter_map(|m| match &m.def {
            MemberDef::List { raw, .. } => Some(raw),
            _ => None,
        })
        .collect();
    let need = super::common::module_need(ir, &module_names, &mut BTreeSet::new());
    let projected = super::module_projection::projections(
        ir,
        &structural.template,
        &need,
        &imports,
        &code,
        &lists,
    );
    let mut module = module_code_with(ir, &module_names, &mut imports, &projected.module);
    // PR2: a projected import is declared here instead of imported.
    let mut projected_modules = Vec::new();
    for (u, (stmt, path)) in projected.imports.iter().filter(|_| project_imports) {
        imports.remove(u);
        module.insert_str(0, &format!("{stmt}\n"));
        projected_modules.push(path.clone());
    }

    // Body declarations (seeds, refs, reached derived values), each after the ones it reads, then in source order
    // (F385). The fourth field is the value the declaration reads names from.
    let mut decls: Vec<(u32, String, String, Option<RawExpr>)> = Vec::new();
    let mut uses_signal = false;
    let mut uses_computed = false;
    // `useId` values arrive from the server in the host's `x-props` (`_id{k}`, S7 step 6). They are
    // read from the attribute once, not from `props()`: an `x-props-bind` link replaces the props.
    for (k, name) in ir.id_bindings.iter().enumerate() {
        decls.push((
            0,
            name.clone(),
            format!(
                "const {name} = JSON.parse({}.getAttribute(\"x-props\") ?? \"{{}}\")._id{k}",
                n.el
            ),
            None,
        ));
    }
    for (i, s) in ir.state.iter().enumerate() {
        // R34.143: a state seeded with the instance's `late` flag (the server markup and a hydrated mount read `init`)
        let init = if s.late {
            n.late.clone()
        } else {
            inits[i]
                .as_ref()
                .map_or("undefined".to_string(), |r| client_js(r, &f))
        };
        let loc = structural.state[i].init.raw_loc().unwrap_or_default();
        decls.push((
            loc,
            s.name.clone(),
            format!("const {} = {}({init})", s.name, n.signal),
            inits[i].clone(),
        ));
        uses_signal = true;
    }
    // F288 G9: a ref whose initial value reads a handler (printed after the decls) starts empty and is set right after the
    // handlers, still at instance setup, before any effect or binding runs.
    let handler_names: BTreeSet<String> = ir.handlers.iter().map(|h| h.name.clone()).collect();
    let mut late_refs: Vec<String> = Vec::new();
    for (i, r) in ir.refs.iter().enumerate() {
        let loc = structural.refs[i].init.raw_loc().unwrap_or_default();
        if let Expr::Raw(raw) = &structural.refs[i].init
            && !super::common::reads_of(raw, &handler_names).is_empty()
        {
            late_refs.push(format!("{}.current = {}", r.name, client_js(raw, &f)));
            decls.push((
                loc,
                r.name.clone(),
                format!(
                    "const {} = {}({})",
                    r.name,
                    n.ref_,
                    crate::ir::expr::js_string(&r.name)
                ),
                None,
            ));
            continue;
        }
        // `useRef(init)` is a cell that starts at `init` (an element attached later replaces it): `null` and
        // `undefined` are the common case of a DOM ref and print as before.
        let _ = r;
        let init = match &structural.refs[i].init {
            Expr::Raw(raw)
                if !matches!(
                    raw.kind,
                    RawKind::Lit(Literal::Null) | RawKind::Lit(Literal::Undefined)
                ) =>
            {
                format!(", {}", client_js(raw, &f))
            }
            _ => String::new(),
        };
        decls.push((
            loc,
            r.name.clone(),
            format!(
                "const {} = {}({}{init})",
                r.name,
                n.ref_,
                crate::ir::expr::js_string(&r.name)
            ),
            match &structural.refs[i].init {
                Expr::Raw(r) | Expr::Server(crate::ir::ServerExpr(r)) => Some(r.clone()),
                _ => None,
            },
        ));
    }
    for d in &structural.derived {
        if !reached.contains(&d.name) {
            continue;
        }
        let (Some(raw), Some((_, shape))) = (f.derived_raw(&d.name), f.derived.get(&d.name)) else {
            continue;
        };
        let line = match shape {
            DerivedShape::Value => {
                uses_computed = true;
                format!(
                    "const {} = {}(() => {})",
                    d.name,
                    n.computed,
                    arrow_body(&client_js(raw, &f))
                )
            }
            DerivedShape::Function => format!("const {} = {}", d.name, client_fn(raw, &f)),
        };
        decls.push((raw.loc, d.name.clone(), line, Some(raw.clone())));
    }
    // The view `s` a verbatim body reads: live getters over the store's signals and computeds.
    for u in &ir.stores {
        let (Some(v), Some(r)) = (&u.view, &u.resolved) else {
            continue;
        };
        if !views.contains(&(u.handle.clone(), v.clone())) {
            continue;
        }
        let mut keys: Vec<&String> = r.signals.iter().chain(&r.computeds).collect();
        keys.sort();
        keys.dedup();
        let getters: Vec<String> = keys
            .iter()
            .map(|k| {
                format!(
                    "get {}() {{ return {} }}",
                    object_key(k),
                    store_client_js(&u.handle, Some(k), &f)
                )
            })
            .collect();
        decls.push((
            u.loc,
            v.clone(),
            format!("const {v} = {{ {} }}", getters.join(", ")),
            None,
        ));
    }
    let names: BTreeSet<String> = decls.iter().map(|d| d.1.clone()).collect();
    let decls = super::common::order_decls(
        decls
            .into_iter()
            .map(|(loc, name, line, raw)| {
                let reads = raw
                    .as_ref()
                    .map(|r| super::common::reads_of(r, &names))
                    .unwrap_or_default();
                (loc, name, reads, line)
            })
            .collect(),
    );

    let mut helpers: BTreeSet<Helper> = BTreeSet::new();
    let mut uses_untracked = false;
    let mut body: Vec<String> = decls;
    let mut exported: Vec<String> = Vec::new();
    // x-model writes the signal: every state is a member.
    exported.extend(ir.state.iter().map(|s| s.name.clone()));
    for h in &ir.handlers {
        let mut params: Vec<String> = h.item_scoped.clone();
        params.push(format!("...{}", f.rest));
        body.push(format!(
            "const {} = ({}) => ({})(...{})",
            h.name,
            params.join(", "),
            client_fn(&h.body, &f),
            f.rest
        ));
        exported.push(h.name.clone());
    }
    body.extend(late_refs);
    exported.extend(
        event_locals
            .iter()
            .filter(|n| reached.contains(*n))
            .cloned(),
    );
    for m in members {
        let line = match &m.def {
            MemberDef::Value {
                raw,
                bindings,
                negate,
                paint,
            } => {
                let js = client_js(raw, &f);
                let js = if *negate { format!("!({js})") } else { js };
                // Written the way the server painted it (the runtime writes String(v)).
                let js = match paint {
                    Paint::Raw => js,
                    p => {
                        let h = Helper::of(*p);
                        helpers.insert(h);
                        format!("{}({js})", n.helper(h))
                    }
                };
                if bindings.is_empty() {
                    uses_computed = true;
                    format!(
                        "const {} = {}(() => {})",
                        m.name,
                        n.computed,
                        arrow_body(&js)
                    )
                } else {
                    format!(
                        "const {} = ({}) => {}",
                        m.name,
                        bindings.join(", "),
                        arrow_body(&js)
                    )
                }
            }
            MemberDef::List { raw, bindings } if bindings.is_empty() => {
                uses_computed = true;
                format!(
                    "const {} = {}(() => {})",
                    m.name,
                    n.computed,
                    arrow_body(&client_js(raw, &f))
                )
            }
            MemberDef::List { raw, bindings } => format!(
                "const {} = ({}) => {}",
                m.name,
                bindings.join(", "),
                arrow_body(&client_js(raw, &f))
            ),
            MemberDef::Key { raw, item } => {
                format!(
                    "const {} = ({item}) => {}",
                    m.name,
                    arrow_body(&client_js(raw, &f))
                )
            }
            MemberDef::Link { props, bindings } => {
                let fields: Vec<String> = props
                    .iter()
                    .map(|(k, r)| {
                        if k == crate::ir::SPREAD_KEY {
                            // `<Child {...x} />` (shadcn S1.2): the props object spreads as in JS.
                            return format!("...{}", spread_js(r, &f));
                        }
                        let v = if super::common::is_function_raw(r)
                            || matches!(
                                &r.kind,
                                crate::ir::RawKind::Ident {
                                    kind: crate::ir::IdentKind::Setter,
                                    ..
                                }
                            ) {
                            client_fn(r, &f)
                        } else {
                            client_js(r, &f)
                        };
                        format!("{}: {v}", object_key(k))
                    })
                    .collect();
                let obj = format!("({{ {} }})", fields.join(", "));
                if bindings.is_empty() {
                    uses_computed = true;
                    format!("const {} = {}(() => {obj})", m.name, n.computed)
                } else {
                    format!("const {} = ({}) => {obj}", m.name, bindings.join(", "))
                }
            }
        };
        body.push(line);
        exported.push(m.name.clone());
    }
    for e in &ir.effects {
        // The effect body is bound per run (a cleanup it returns passes through).
        let run = format!("({})()", client_js(&e.body, &f));
        body.push(match &e.deps {
            // React re-runs it on every render: track every read.
            None => format!("{}(() => {run})", n.effect),
            // Re-run only when a dependency changes; the body is untracked.
            Some(deps) => {
                uses_untracked = true;
                let d: Vec<String> = deps.iter().map(|d| client_js(d, &f)).collect();
                format!(
                    "{}(() => {{ void [{}]; return {}(() => {run}) }})",
                    n.effect,
                    d.join(", "),
                    n.untracked
                )
            }
        });
    }
    let mut seen = BTreeSet::new();
    exported.retain(|m| seen.insert(m.clone()));

    let mut rt = Vec::new();
    if uses_signal {
        rt.push(import_as("signal", &n.signal));
    }
    if uses_computed {
        rt.push(import_as("computed", &n.computed));
    }
    if uses_untracked {
        rt.push(import_as("untracked", &n.untracked));
    }
    if !shared {
        rt.push(import_as("defineBehavior", &n.define));
    }
    let mut out = if shared {
        "// generated by brust v2 — shared client factory\n".to_string()
    } else {
        format!("// generated by brust v2 — client chunk for {}\n", ir.id)
    };
    out.push_str(&format!(
        "import {{ {} }} from {}\n",
        rt.join(", "),
        crate::ir::expr::js_string(runtime_import)
    ));
    out.push_str(&import_lines(&imports));
    out.push_str(&module);
    for h in &helpers {
        out.push_str(&helper(*h, &n));
        out.push('\n');
    }
    // The context's names are the allocator's (`__el`, `props`, … unless the component spells one).
    let ctx = format!(
        "{{ el: {}, {}, effect: {}, onCleanup: {}, ref: {}{}{} }}",
        n.el,
        if n.props == "props" {
            "props".to_string()
        } else {
            format!("props: {}", n.props)
        },
        n.effect,
        n.on_cleanup,
        n.ref_,
        if ir.state.iter().any(|s| s.late) {
            format!(", late: {}", n.late)
        } else {
            String::new()
        },
        // R34.140: `useCollection(scope)` lowered to a handler that calls this
        if ir.uses_collection {
            format!(", items: {}", crate::ir::COLLECTION_ITEMS)
        } else {
            String::new()
        }
    );
    if shared {
        if n.behavior == "behavior" {
            out.push_str(&format!("export const behavior = ({ctx}) => {{\n"));
        } else {
            out.push_str(&format!("const {} = ({ctx}) => {{\n", n.behavior));
        }
    } else {
        out.push_str(&format!(
            "export default {}({}, ({ctx}) => {{\n",
            n.define,
            crate::ir::expr::js_string(&ir.id)
        ));
    }
    for line in &body {
        out.push_str("  ");
        out.push_str(line);
        out.push('\n');
    }
    out.push_str(&format!(
        "  return {{ {} }}\n}}{}\n",
        exported.join(", "),
        if shared { "" } else { ")" }
    ));
    if shared && n.behavior != "behavior" {
        out.push_str(&format!("export {{ {} as behavior }}\n", n.behavior));
    }
    (out, exported, projected_modules)
}

/// A module-level helper that writes a value the way the server painted it.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
enum Helper {
    // In the order the chunk prints them.
    Attr,
    Attro,
    Attrs,
    Bool,
    Css,
    Text,
}

impl Helper {
    fn of(p: Paint) -> Helper {
        match p {
            Paint::Text => Helper::Text,
            Paint::Attr => Helper::Attr,
            Paint::AttrStr => Helper::Attrs,
            Paint::AttrOver => Helper::Attro,
            Paint::Style => Helper::Css,
            Paint::Bool | Paint::Raw => Helper::Bool,
        }
    }
}

/// F233: the names the chunk declares itself, each the allocator's (the plain spelling unless the component spells it).
struct ChunkNames {
    signal: String,
    computed: String,
    untracked: String,
    define: String,
    behavior: String,
    el: String,
    props: String,
    effect: String,
    on_cleanup: String,
    late: String,
    ref_: String,
    text: String,
    attr: String,
    attrs: String,
    attro: String,
    css: String,
    unitless: String,
    bool_: String,
    args: String,
}

impl ChunkNames {
    fn new(n: &mut Names) -> Self {
        ChunkNames {
            signal: n.fresh("signal"),
            computed: n.fresh("computed"),
            untracked: n.fresh("untracked"),
            define: n.fresh("defineBehavior"),
            behavior: n.fresh("behavior"),
            el: n.fresh("__el"),
            props: n.fresh("props"),
            effect: n.fresh("__effect"),
            on_cleanup: n.fresh("__onCleanup"),
            late: n.fresh("__late"),
            ref_: n.fresh("__ref"),
            text: n.fresh("__text"),
            attr: n.fresh("__attr"),
            attrs: n.fresh("__attrs"),
            attro: n.fresh("__attro"),
            css: n.fresh("__css"),
            unitless: n.fresh("__unitless"),
            bool_: n.fresh("__bool"),
            args: n.fresh("__args"),
        }
    }

    fn helper(&self, h: Helper) -> &str {
        match h {
            Helper::Text => &self.text,
            Helper::Attr => &self.attr,
            Helper::Attrs => &self.attrs,
            Helper::Attro => &self.attro,
            Helper::Css => &self.css,
            Helper::Bool => &self.bool_,
        }
    }
}

/// `signal`, or `signal as signal1` when the chunk renamed it.
fn import_as(name: &str, local: &str) -> String {
    if name == local {
        name.to_string()
    } else {
        format!("{name} as {local}")
    }
}

/// The source of helper `h` under the chunk's names.
fn helper(h: Helper, n: &ChunkNames) -> String {
    match h {
        // x-text: booleans paint as nothing, arrays concatenate (React).
        Helper::Text => format!(
            "const {t} = (v) => (typeof v === \"boolean\" ? \"\" : Array.isArray(v) ? v.map({t}).join(\"\") : v)",
            t = n.text
        ),
        // x-bind: a boolean removes the attribute, like null (React omits true and false on a plain attribute).
        Helper::Attr => format!(
            "const {} = (v) => (typeof v === \"boolean\" ? null : v)",
            n.attr
        ),
        // boolean attributes: truthy sets it, falsy (0, "", null) removes it, as React does.
        Helper::Bool => format!("const {} = (v) => !!v", n.bool_),
        // aria-*, data-*, draggable, ...: React writes the booleans as the strings.
        Helper::Attrs => format!(
            "const {} = (v) => (typeof v === \"boolean\" ? String(v) : v)",
            n.attrs
        ),
        // download, capture: true is the empty value, false removes it.
        Helper::Attro => format!(
            "const {} = (v) => (v === true ? \"\" : v === false ? null : v)",
            n.attro
        ),
        // x-bind-style of a style object: brust-jinja's style_obj_to_css rule (the unitless list is its `UNITLESS`;
        // a vendor-prefixed name counts as its bare one, `msX` hyphenates as `-ms-x`, a string value is trimmed).
        Helper::Css => format!(
            concat!(
                "const {u} = new Set(\"{list}\".split(\" \"))\n",
                "const {c} = (o) => Object.entries(o !== null && typeof o === \"object\" ? o : {{}})\n",
                "  .filter(([k, v]) => v != null && v !== false && /^(--[A-Za-z0-9_-]+|[A-Za-z][A-Za-z0-9_-]*)$/.test(k))\n",
                "  .map(([k, v]) => [k, typeof v === \"number\" ? (v === 0 || {u}.has(k.replace(/^(Webkit|Moz|ms|O)(?=[A-Z])/, \"\").replace(/^./, (c) => c.toLowerCase())) || k.startsWith(\"--\") ? String(v) : v + \"px\") : typeof v === \"boolean\" ? \"\" : String(v).trim()])\n",
                "  .filter(([, v]) => v !== \"\" && !/[;{{}}\\\\\\n\\r]|\\/\\*|expression\\(|@import/i.test(v))\n",
                "  .map(([k, v]) => (k.startsWith(\"--\") ? k : k.replace(/[A-Z]/g, (c) => \"-\" + c.toLowerCase()).replace(/^ms-/, \"-ms-\")) + \":\" + v)\n",
                "  .join(\";\")"
            ),
            list = brust_jinja::UNITLESS.join(" "),
            u = n.unitless,
            c = n.css
        ),
    }
}

fn object_key(k: &str) -> String {
    let ident = k
        .chars()
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_' || c == '$')
        && k.chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$');
    if ident {
        k.to_string()
    } else {
        crate::ir::expr::js_string(k)
    }
}

/// Handler names the template's `x-on-*` directives use.
fn event_handlers(n: &Node) -> Vec<String> {
    let mut out = Vec::new();
    fn walk(n: &Node, out: &mut Vec<String>) {
        match n {
            Node::Element {
                attrs, children, ..
            } => {
                for a in attrs {
                    if let Attr::Event { handler, .. } = a
                        && !out.contains(handler)
                    {
                        out.push(handler.clone());
                    }
                }
                children.iter().for_each(|c| walk(c, out));
            }
            Node::If { then, else_, .. } => then.iter().chain(else_).for_each(|c| walk(c, out)),
            Node::For { body, .. } => body.iter().for_each(|c| walk(c, out)),
            Node::Component { children, .. } | Node::Fragment(children) => {
                children.iter().for_each(|c| walk(c, out))
            }
            Node::Text(_) | Node::Slot(_) | Node::Outlet => {}
        }
    }
    walk(n, &mut out);
    out
}

#[allow(dead_code)]
fn _expr(_: &Expr) {}

/// The chunk's value of a spread source: the whole props signal, the props minus the names the
/// pattern binds (`...rest`), or a props path.
fn spread_js(r: &RawExpr, f: &Facts<'_>) -> String {
    match &r.kind {
        crate::ir::RawKind::Ident {
            name,
            kind: crate::ir::IdentKind::Prop,
        } if name == "*" => format!("{}()", f.props_fn),
        crate::ir::RawKind::Ident {
            name,
            kind: crate::ir::IdentKind::Prop,
        } if name == crate::ir::REST_PROPS => {
            let named: Vec<String> =
                f.ir.props
                    .iter()
                    .enumerate()
                    .map(|(i, p)| format!("{}: _{i}", crate::ir::expr::js_string(&p.name)))
                    .collect();
            format!(
                "(({{ {}...r }}) => r)({}())",
                named.iter().map(|n| format!("{n}, ")).collect::<String>(),
                f.props_fn
            )
        }
        _ => format!("({})", client_js(r, f)),
    }
}
