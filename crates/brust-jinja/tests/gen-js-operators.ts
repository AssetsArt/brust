// Regenerates crates/brust-jinja/tests/js_operators_table.rs: every operator of F428 over a grid of operands, with the
// expected result computed by JS itself (this script). Run: `bun crates/brust-jinja/tests/gen-js-operators.ts`.
const values: [string, () => unknown][] = [
  ['undefined', () => undefined],
  ['none', () => null],
  ['true', () => true],
  ['false', () => false],
  ['0', () => 0],
  ['1', () => 1],
  ['-1', () => -1],
  ['1.5', () => 1.5],
  ['2', () => 2],
  ["''", () => ''],
  ["'5'", () => '5'],
  ["' 7 '", () => ' 7 '],
  ["'abc'", () => 'abc'],
  ["'a'", () => 'a'],
  ["'b'", () => 'b'],
  ["'10'", () => '10'],
  ["'9'", () => '9'],
  ["'0x10'", () => '0x10'],
  ["'1e3'", () => '1e3'],
  ["'Infinity'", () => 'Infinity'],
  ["'inf'", () => 'inf'],
  ["'nan'", () => 'nan'],
  ['[]', () => []],
  ['[5]', () => [5]],
  ['[1, 2]', () => [1, 2]],
  ['{}', () => ({})],
]
const rows: string[] = []
const add = (expr: string, want: unknown) => rows.push(`    (${JSON.stringify(expr)}, ${JSON.stringify(String(want))}),`)
const bins: [string, (a: any, b: any) => unknown][] = [
  ['js_sub', (a, b) => a - b],
  ['js_mul', (a, b) => a * b],
  ['js_eq', (a, b) => a == b],
  ['js_seq', (a, b) => a === b],
]
for (const [f, fn] of bins) for (const [aj, av] of values) for (const [bj, bv] of values) add(`(${aj}) | ${f}(${bj})`, fn(av(), bv()))
const cmps: Record<string, (a: any, b: any) => boolean> = { '<': (a, b) => a < b, '<=': (a, b) => a <= b, '>': (a, b) => a > b, '>=': (a, b) => a >= b }
for (const [op, fn] of Object.entries(cmps)) for (const [aj, av] of values) for (const [bj, bv] of values) add(`(${aj}) | js_cmp(${bj}, '${op}')`, fn(av(), bv()))
for (const [aj, av] of values) {
  const n = -(av() as any)
  add(`(${aj}) | js_neg`, n === 0 ? 0 : n)
  add(`(${aj}) | js_num`, +(av() as any))
}
await Bun.write(
  new URL('./js_operators_table.rs', import.meta.url),
  `// Generated by gen-js-operators.ts (expected values computed by JS). Do not edit.\n// F428: each brust-jinja JS-operator filter over a grid of operands equals JS.\npub const TABLE: &[(&str, &str)] = &[\n${rows.join('\n')}\n];\n`,
)
console.log(rows.length, 'rows')
