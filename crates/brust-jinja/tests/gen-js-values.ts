// Regenerates crates/brust-jinja/tests/js_values_table.rs (F585): the values JSON cannot carry (NaN, ±Infinity, a
// bigint), decoded from the job wrapper's tag, through every filter the template subset prints, against a grid of other
// operands; the expected text is computed by JS itself (`ERR` = JS throws). Run: `bun crates/brust-jinja/tests/gen-js-values.ts`.
const specials: [string, () => unknown][] = [
  ['nan', () => NaN],
  ['inf', () => Infinity],
  ['ninf', () => -Infinity],
  ['b10', () => 10n],
  ['b0', () => 0n],
  ['bneg', () => -3n],
]
const others: [string, () => unknown][] = [
  ['undefined', () => undefined],
  ['none', () => null],
  ['true', () => true],
  ['false', () => false],
  ['0', () => 0],
  ['1', () => 1],
  ['-1', () => -1],
  ['1.5', () => 1.5],
  ['10', () => 10],
  ["''", () => ''],
  ["'5'", () => '5'],
  ["'10'", () => '10'],
  ["'abc'", () => 'abc'],
  ["'0x10'", () => '0x10'],
  ["'Infinity'", () => 'Infinity'],
  ['[]', () => []],
  ['[5]', () => [5]],
  ['{}', () => ({})],
]
const all = [...specials, ...others]
const rows: string[] = []
const run = (f: () => unknown): string => {
  try {
    return String(f())
  } catch {
    return 'ERR'
  }
}
const add = (expr: string, want: string) => rows.push(`    (${JSON.stringify(expr)}, ${JSON.stringify(want)}),`)
const bins: [string, (a: any, b: any) => unknown][] = [
  ['js_add', (a, b) => a + b],
  ['js_sub', (a, b) => a - b],
  ['js_mul', (a, b) => a * b],
  ['js_div', (a, b) => a / b],
  ['js_mod', (a, b) => a % b],
  ['js_eq', (a, b) => a == b],
  ['js_seq', (a, b) => a === b],
]
const cmps: Record<string, (a: any, b: any) => boolean> = { '<': (a, b) => a < b, '<=': (a, b) => a <= b, '>': (a, b) => a > b, '>=': (a, b) => a >= b }
// Every pair with at least one special operand, both orders.
const pairs: [[string, () => unknown], [string, () => unknown]][] = []
for (const a of specials) for (const b of all) pairs.push([a, b])
for (const a of others) for (const b of specials) pairs.push([a, b])
for (const [[aj, av], [bj, bv]] of pairs) {
  for (const [f, fn] of bins) add(`(${aj}) | ${f}(${bj})`, run(() => fn(av(), bv())))
  for (const [op, fn] of Object.entries(cmps)) add(`(${aj}) | js_cmp(${bj}, '${op}')`, run(() => fn(av(), bv())))
}
// One-operand filters: unary operators, String(), and how React prints / tests the value.
for (const [aj, av] of specials) {
  const v = av() as any
  add(`(${aj}) | js_neg`, run(() => -v))
  add(`(${aj}) | js_num`, run(() => +v))
  add(`(${aj}) | js_string`, String(v))
  add(`(${aj}) | js_str`, String(v)) // a text child: React prints String(v) for a number and a bigint
  add(`(${aj}) | attr_str`, String(v)) // an attribute value: String(v)
  add(`(${aj}) | e`, String(v))
  add(`(${aj}) | truthy`, String(!!v))
  add(`(${aj}) | present_plain`, 'true')
  add(`(${aj}) | present_str`, 'true')
  add(`(${aj}) | present`, 'true')
  add(`[${aj}, 1] | join('-')`, [v, 1].join('-'))
  // json_attr writes attribute text: the JSON the client parses, its quotes escaped.
  add(`(${aj}) | json_attr`, JSON.stringify(typeof v === 'bigint' ? v.toString() : v).replaceAll('"', '&quot;'))
}
await Bun.write(
  new URL('./js_values_table.rs', import.meta.url),
  `// Generated by gen-js-values.ts (expected values computed by JS). Do not edit.\n// F585: NaN, ±Infinity and bigint job values through each template filter equal JS.\npub const TABLE: &[(&str, &str)] = &[\n${rows.join('\n')}\n];\n`,
)
console.log(rows.length, 'rows')
