// F428/F427: JS operators on the server. The page prints each expression below through the real `brust build` + `start`; the
// expected text is the same expression evaluated by JS here (`String(value)`), so every operator family, the cases jinja
// answered with HTTP 500 (`'10' - 9`, `-'10'`, `null - 9`, a string against a number) and the number printing (`NaN`,
// `Infinity`, `-0` as `0`, exponent forms) are compared to JS itself. Page.tsx is generated from this table (the test
// rewrites it when it differs). Run alone: `bun test --timeout 180000 tests/server/js-operators.test.ts`.
import { afterAll, beforeAll, expect, test } from 'bun:test'
import { readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const app = join(import.meta.dir, '../../packages/brust/test/fixtures/js-operators')
const bin = join(import.meta.dir, '../../packages/brust/bin/brust')
const props = { s: '10', t: '9', n: 9, q: '9', nl: null, zero: 0, b: true, x: 3, big: 1e308 }
/** [expression, is boolean]: a boolean prints through a ternary, as React prints nothing for `true`. */
const EXPRS: [string, boolean][] = [
  ['s - n', false], ['n - s', false], ['s * n', false], ['u * n', false], ['nl - n', false], ['-s', false], ['+s', false],
  ['s * 2', false], ['n / zero', false], ['-zero', false], ['zero / zero', false], ['n % zero', false], ['-n % 4', false],
  ['x * 0.1', false], ['big * n', false], ['big * -n', false], ['x * 1e21', false], ['x / 1e7', false], ['s + n', false], ['n + q', false],
  ['s > n', true], ['s > t', true], ['nl < n', true], ['u < n', true], ['n >= 9', true], ["'b' > 'a'", true], ['s <= q', true],
  ['n == q', true], ['n === q', true], ['nl == u', true], ['nl === u', true], ['b == 1', true], ['b === 1', true], ["s === '10'", true], ["s !== '10'", true], ['n != q', true], ['n !== q', true],
]

const pageSource = () =>
  `// Generated by tests/server/js-operators.test.ts from its EXPRS table. Do not edit.\n` +
  `export default function Page({ s, t, n, q, nl, zero, b, x, big }: any) {\n  const u: any = undefined\n  return (\n    <main>\n` +
  EXPRS.map(([e, bool], i) => `      <p data-i="${i}">{${bool ? `${e} ? 'true' : 'false'` : e}}</p>\n`).join('') +
  `    </main>\n  )\n}\n`

const expected = () => {
  const names = Object.keys(props)
  return EXPRS.map(([e, bool]) => {
    const v = new Function(...names, 'u', `return (${e})`)(...Object.values(props), undefined)
    return bool ? String(Boolean(v)) : String(v)
  })
}

const shellEnv = () => {
  const { NODE_ENV: _n, ...rest } = process.env
  return { ...rest, BRUST_PORT: '', BRUST_WORKERS: '', BRUST_ADDR: '' }
}
let proc: ReturnType<typeof Bun.spawn> | undefined
let base = ''

beforeAll(async () => {
  const file = join(app, 'Page.tsx')
  const want = pageSource()
  let have = ''
  try { have = readFileSync(file, 'utf8') } catch {}
  if (have !== want) writeFileSync(file, want)
  const b = Bun.spawnSync([bin, 'build', 'routes.tsx'], { cwd: app, env: shellEnv(), stdout: 'pipe', stderr: 'pipe' })
  if (b.exitCode !== 0) throw new Error(`brust build failed:\n${b.stderr.toString()}`)
  proc = Bun.spawn([bin, 'start', '--port', '0', '--workers', '1'], { cwd: app, env: shellEnv(), stdout: 'pipe', stderr: 'pipe' })
  const reader = (proc.stdout as ReadableStream<Uint8Array>).getReader()
  const dec = new TextDecoder()
  let out = ''
  while (!/\[brust\] ready/.test(out) || !/listening on (\S+)/.test(out)) {
    const { done, value } = await reader.read()
    if (done) throw new Error(`brust start exited:\n${out}`)
    out += dec.decode(value, { stream: true })
  }
  void (async () => { for (;;) { const { done } = await reader.read(); if (done) return } })()
  base = `http://${/listening on (\S+)/.exec(out)![1]}`
}, 180_000)

afterAll(async () => {
  if (proc) {
    proc.kill('SIGINT')
    if ((await Promise.race([proc.exited, Bun.sleep(5000).then(() => undefined)])) === undefined) { proc.kill('SIGKILL'); await proc.exited }
  }
  rmSync(join(app, 'dist'), { recursive: true, force: true })
})

test('every operator prints what JS computes (and answers 200)', async () => {
  const res = await fetch(`${base}/`)
  expect(res.status).toBe(200)
  const html = await res.text()
  const got = EXPRS.map((_, i) => new RegExp(`<p data-i="${i}">([^<]*)</p>`).exec(html)?.[1])
  const want = expected()
  const bad = EXPRS.flatMap(([e], i) => (got[i] === want[i] ? [] : [`${e}: got ${got[i]}, JS ${want[i]}`]))
  expect(bad).toEqual([])
}, 60_000)
