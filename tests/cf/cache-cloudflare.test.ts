// @brust/cache-cloudflare inside a built Worker under local workerd: KV + DO (kvdo) and the DO store (do). Lane A's Workers cases re-run with the
// real adapters, plus the epoch gen change and the new-isolate floor (R6). Opt-in: BRUST_CF_E2E=1.
import { afterAll, beforeAll, describe, expect, test } from 'bun:test'
import { mkdtempSync, readFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { startWrangler, type Wrangler } from './pokedex-d1/remote'
import { WRANGLER } from './tools'

const ENABLED = process.env.BRUST_CF_E2E === '1'
const APP = resolve(import.meta.dir, '../fixtures/cf-cache')
const MAIN_JS = '// generated by brust build --target cloudflare (do not edit)\nexport * from "./index.js"\nexport { default } from "./index.js"\nexport { BrustCacheDO } from "./brust-app.js"\n'
const ENV = { ...process.env, WRANGLER_SEND_METRICS: 'false', CI: '1' }

type L2 = Record<string, number>
async function until<T>(what: string, f: () => Promise<T | undefined>, ms = 8000): Promise<T> {
  const t0 = Date.now()
  for (;;) {
    const v = await f()
    if (v !== undefined) return v
    if (Date.now() - t0 > ms) throw new Error(`timed out: ${what}`)
    await Bun.sleep(50)
  }
}
/** epoch_interval_ms is 250: a sleep of 400 ms is only a lower bound for the next poll + the RPC. */
const nextPoll = () => Bun.sleep(400)

describe.skipIf(!ENABLED)('cf-cache: @brust/cache-cloudflare on local workerd', () => {
  let ready = process.env.BRUST_CF_WASM_READY === '1'
  for (const variant of ['kvdo', 'do'] as const) {
    describe(variant, () => {
      const CF = join(APP, `dist-${variant}`, 'cf')
      const CONFIG = join(CF, 'wrangler.jsonc')
      let state = ''
      let w: Wrangler
      let base = ''
      const get = (path: string, init?: RequestInit) => fetch(base + path, { redirect: 'manual', ...init })
      const S = async () => (await (await get('/_brust/cache/stats')).json()) as { loader_calls: number; l2: L2 }
      const post = (path: string, body: unknown) => get(`/_brust/action${path}`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) })
      const doState = async () => (await (await get('/_brust/action/e2e/state')).json()) as { publishes: number; seq: number; gen: string }
      const l1Clear = async () => expect((await get('/__brust_e2e/l1-clear')).status).toBe(204)
      const remote = async (args: unknown) => (await post('/e2e/remote', { args, fanout: variant === 'do' })).text()
      const cacheHeader = async (path: string) => {
        const r = await get(path)
        await r.text()
        return r.headers.get('x-brust-cache')
      }
      const written = async (n: number) => until('the write-through', async () => (((await S()).l2.sets ?? 0) >= n ? true : undefined))
      const start = async () => {
        w = await startWrangler({ config: CONFIG, state })
        base = w.base
      }

      beforeAll(async () => {
        state = mkdtempSync(join(tmpdir(), `cf-cache-${variant}-`))
        const b = Bun.spawnSync(['bun', join(APP, 'scripts/build-cf.ts'), variant], { cwd: APP, env: { ...process.env, ...(ready ? { BRUST_CF_WASM_READY: '1' } : {}) }, stdout: 'inherit', stderr: 'inherit' })
        if (b.exitCode !== 0) throw new Error(`build-cf ${variant} exited ${b.exitCode}`)
        ready = true
        await start()
      }, 600_000)
      afterAll(async () => {
        await w?.stop()
        rmSync(state, { recursive: true, force: true })
      })

      test('1 MISS, then (L1 cleared) HIT-L2 with the same body and no loader, then HIT', async () => {
        const a = await get('/items/7')
        expect(a.headers.get('x-brust-cache')).toBe('MISS')
        const html = await a.text()
        await written(1)
        const loaders = (await S()).loader_calls
        await l1Clear()
        const b = await get('/items/7')
        expect(b.headers.get('x-brust-cache')).toBe('HIT-L2')
        expect(await b.text()).toBe(html)
        expect((await S()).loader_calls).toBe(loaders)
        expect(await cacheHeader('/items/7')).toBe('HIT')
      })

      test("2 another isolate's invalidation is replayed here (received +1) and the page misses", async () => {
        const before = await S()
        await remote({ tags: ['items'] })
        await nextPoll()
        expect(await cacheHeader('/items/7')).toBe('MISS')
        expect((await S()).l2.received).toBe(before.l2.received + 1)
      })

      test('3 after a remote invalidation the old body is not served from L2', async () => {
        await written(2)
        await (await get('/items/7')).text()
        await l1Clear()
        await remote({ tags: ['items'] })
        await nextPoll()
        await l1Clear()
        expect(await cacheHeader('/items/7')).not.toBe('HIT-L2')
      })

      test("4 this isolate's own invalidation: one memoized publish, echo skipped, never re-published (L3)", async () => {
        const before = { s: await S(), d: await doState() }
        expect((await post('/bump', { tag: 'items' })).status).toBe(200)
        await until('the publish', async () => ((await doState()).publishes === before.d.publishes + 1 ? true : undefined))
        await nextPoll()
        await (await get('/items/7')).text()
        await nextPoll()
        await (await get('/items/7')).text()
        const after = await S()
        expect(after.l2.skipped_own).toBe(before.s.l2.skipped_own + 1)
        expect(after.l2.published).toBe(before.s.l2.published + 1)
        expect((await doState()).publishes).toBe(before.d.publishes + 1)
      })

      test('5 a gen change (DO restart) clears tier 1: resets +1 (L2 still holds the body)', async () => {
        await (await get('/items/7')).text()
        expect(await cacheHeader('/items/7')).toBe('HIT')
        const before = await S()
        const g0 = (await doState()).gen
        await (await post('/e2e/regen', {})).text()
        expect((await doState()).gen).not.toBe(g0)
        await nextPoll()
        expect(await cacheHeader('/items/7')).not.toBe('HIT')
        expect((await S()).l2.resets).toBe(before.l2.resets + 1)
      })

      test('6 a NEW isolate does not serve a body invalidated before it started (R6 floor, persisted seq)', async () => {
        await (await get('/items/7')).text()
        await written((await S()).l2.sets ?? 0)
        const html = await get('/items/7')
        await html.text()
        await remote({ tags: ['items'] })
        await w.stop()
        await start() // same --persist-to: the DO seq + floors and the KV entry survive; the isolate is new
        expect(await cacheHeader('/items/7')).not.toBe('HIT-L2')
        await nextPoll()
        expect((await S()).l2.epoch_polls).toBeGreaterThanOrEqual(1)
      })

      test('7 worker/main.js is the 3-line re-export and wrangler deploy --dry-run bundles it', () => {
        expect(readFileSync(join(CF, 'worker', 'main.js'), 'utf8')).toBe(MAIN_JS)
        const dry = Bun.spawnSync(['bunx', WRANGLER, 'deploy', '--dry-run', '--outdir', join(state, 'bundle'), '-c', CONFIG], { cwd: CF, env: ENV })
        expect(dry.exitCode).toBe(0)
        expect(dry.stdout.toString() + dry.stderr.toString()).toMatch(/Total Upload/)
      }, 120_000)
    })
  }
})
